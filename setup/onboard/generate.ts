// Makes bwat's onboarding formats from the master (docs/onboarding/master.md) and the
// templates beside it. `./bwat docs` runs this file; a test fails when a committed file
// differs from what outputs() makes.
//
// A template is Markdown, copied as is except for these slots, each alone on its line:
//   {{steps ids=a,b flows=local,server level=4 show=title,text,fields,commands,shots,checks,when}}
//       the master's steps (all, those whose flows include one of flows=, or those in ids=, in the
//       master's order); level= is the heading's depth (default 3); show= defaults to everything
//       (the step's text is always shown; a prompt format keeps only the lines show= names)
//       format=claude-page|claude-terminal turns each step into a line of a Claude Code prompt instead
//       (inside a ```text fence in the template; see promptStep)
//   {{part ID level=3}}       a part of the master under a heading of that depth (0: no heading)
//   <!-- bwat:snippet NAME --> text <!-- bwat:end-snippet -->   defines text shown nowhere itself;
//   {{snippet NAME}}          places it (the rules for Claude, once, at the top of every prompt)
// Between <!-- bwat:keep NAME --> and <!-- bwat:end-keep --> the template holds a hand-written part:
// the generator copies what the committed output holds there, so a regeneration never touches it.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONDITIONS } from './conditions.ts';
import { attributes, escape, FLOWS, loadMaster, type Master, type Step } from './flow.ts';
import { PLATFORMS } from './platform.ts';
import { ROOT } from './root.ts';

export type Format = 'guide' | 'claude-page' | 'claude-terminal';

/** What ticks a step on its own; static/page.js keeps its own copy of these words. */
export const CHECK_TEXT: Record<string, string> = {
  'prep-complete': 'This step ticks itself once ./bwat prep --check says complete.',
  'bot-built': 'This step ticks itself once the meeting bot is built from the SDK.',
  'edge-healthy': 'This step ticks itself once bwat answers at its address.',
  'owner-signed-in': 'This step ticks itself once the first person has signed in.',
  'claude-connected': 'This step ticks itself once a Claude Code session signed in to bwat has checked in with it.',
  'zoom-ready': 'This step ticks itself once bwat has verified the Zoom setup.',
  'first-card': 'This step ticks itself when bwat writes its first card.',
  'openrouter-key': 'This step ticks itself once OpenRouter takes the saved key.',
};

export const generatedBy = (template: string) =>
  `<!-- Generated by ./bwat docs from docs/onboarding/master.md and docs/onboarding/templates/${template}; edit those, then run ./bwat docs. -->`;

const SHOW = ['title', 'text', 'fields', 'commands', 'shots', 'checks', 'when'];
const DIRECTIVE = /^(\s*)<!--\s*bwat:([\w-]+)(.*?)-->\s*$/;
const RUN_FENCE = /^(\s*)```sh \{bwat-run=[a-z0-9-]+\}\s*$/;
const SHOTS_DIR = 'docs/onboarding/shots';

function captions(): Map<string, string> {
  const shots = JSON.parse(readFileSync(join(ROOT, SHOTS_DIR, 'shots.json'), 'utf8')) as { name: string; caption: string }[];
  return new Map(shots.map((s) => [s.name, s.caption]));
}

/** A step's or part's Markdown as the guide shows it. */
function guideBody(markdown: string, show: Set<string>): string {
  const lines = markdown.split('\n');
  const out: string[] = [];
  let inTable = false;
  const blank = () => { if (out.length && out[out.length - 1] !== '') out.push(''); };
  const push = (line: string) => { out.push(line); if (line !== '') inTable = false; };
  const alone = (indent: string, text: string) => { blank(); push(indent + text); out.push(''); };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    const run = line.match(RUN_FENCE);
    if (run) {
      const end = lines.findIndex((l, j) => j > i && /^\s*```\s*$/.test(l));
      const stop = end < 0 ? lines.length - 1 : end;
      if (show.has('commands')) {
        push(`${run[1]}\`\`\`sh`);
        for (const l of lines.slice(i + 1, stop + 1)) push(l);
      }
      i = stop;
      continue;
    }
    const d = line.match(DIRECTIVE);
    if (!d) { push(line); continue; }
    const [, indent, kind, rest] = d as unknown as [string, string, string, string];
    const value = rest.trim();
    if (kind === 'answer' || kind === 'secret') {
      let j = i + 1;
      while (j < lines.length && lines[j]!.trim() === '') j++;
      const paragraph: string[] = [];
      while (j < lines.length && lines[j]!.trim() !== '' && !DIRECTIVE.test(lines[j]!) && !RUN_FENCE.test(lines[j]!)) paragraph.push(lines[j++]!.trim());
      if (paragraph.length) i = j - 1;
      if (!show.has('fields')) continue;
      let note = paragraph.join(' ').replace(/\|/g, '\\|');
      // A secret is marked, not explained: the answers file step says once what the mark means.
      if (inTable) { while (out[out.length - 1] === '') out.pop(); }
      else { blank(); out.push(`${indent}| Field | Value |`, `${indent}|---|---|`); }
      out.push(`${indent}| ${kind === 'secret' ? '🔒 ' : ''}\`${value}\` | ${note} |`);
      inTable = true;
    } else if (kind === 'shot') {
      const caption = captions().get(value);
      if (show.has('shots') && caption !== undefined && existsSync(join(ROOT, SHOTS_DIR, `${value}.png`))) alone(indent, `![${caption}](onboarding/shots/${value}.png)`);
    } else if (kind === 'when') {
      if (show.has('when')) alone(indent, `Only when ${CONDITIONS[value]?.label ?? value}:`);
    } else if (kind === 'more') {
      // GitHub folds it the same way; the blank lines let the Markdown inside render.
      blank(); push(`${indent}<details>`); push(`${indent}<summary>${escape(attributes(rest).title ?? '')}</summary>`); out.push('');
    } else if (kind === 'end-more') {
      blank(); push(`${indent}</details>`); out.push('');
    } else if (kind === 'flows') {
      if (show.has('when')) alone(indent, `For ${value.split(',').map((f) => FLOWS[f.trim() as keyof typeof FLOWS] ?? f).join('; ')}:`);
    } else if (kind === 'os') {
      if (show.has('when')) alone(indent, `**On ${value.split(',').map((o) => PLATFORMS[o.trim() as keyof typeof PLATFORMS] ?? o).join(' or ')}:**`);
    }
    // check shows nothing (nothing ticks on GitHub: that is the setup page's to say), nor do
    // end-when, end-flows, end-os or any other directive
  }
  while (out.length && out[out.length - 1] === '') out.pop();
  return out.join('\n');
}

function guideStep(step: Step, level: number, show: Set<string>): string {
  const out: string[] = [];
  if (show.has('title')) {
    out.push(`${'#'.repeat(level)} ${step.title}`, '');
    if (step.flows.length < Object.keys(FLOWS).length) out.push(`For: ${step.flows.map((f) => FLOWS[f as keyof typeof FLOWS]).join('; ')}.`, '');
    if (step.when && show.has('when')) out.push(`Only when ${CONDITIONS[step.when]?.label ?? step.when}.`, '');
  }
  if (step.ask) out.push(`${step.ask} If not, skip this step.`, '');
  out.push(guideBody(step.markdown, show));
  return out.join('\n');
}

/** Plain words of a Markdown line: links become their text, and emphasis goes. */
const plain = (line: string) => line
  .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
  .replace(/\*\*|<!--.*?-->/g, '')
  .replace(/\s+/g, ' ');

/** The step's first full sentence: at least four words, capitalised, ending in a full stop; never a fragment or a lead-in ending in a colon. */
function firstSentence(step: Step): string {
  let inFence = false;
  // Folded detail is never the step's summary, nor is text for only some installs or computers.
  // These blocks nest in any order (flow.ts), so a depth, not a flag, says whether one is open.
  let depth = 0;
  for (const raw of step.markdown.split('\n')) {
    const trimmed = raw.trim();
    if (trimmed.startsWith('```')) { inFence = !inFence; continue; }
    const kind = raw.match(DIRECTIVE)?.[2];
    if (kind === 'more' || kind === 'flows' || kind === 'os') { depth += 1; continue; }
    if (kind === 'end-more' || kind === 'end-flows' || kind === 'end-os') { depth -= 1; continue; }
    if (inFence || depth > 0 || !trimmed || DIRECTIVE.test(raw) || /^([>|#]|<!--)/.test(trimmed)) continue;
    const line = plain(trimmed.replace(/^([-*]|\d+\.)\s+/, '')).trim();
    for (const sentence of line.split(/(?<=[.!?])\s+(?=[A-Z`])/)) {
      if (/^[A-Z`]/.test(sentence) && /[.!?]$/.test(sentence) && sentence.split(' ').length >= 4) return sentence;
    }
  }
  return '';
}

/** The answer and secret keys inside a flows block for none of flows, which a prompt for those flows never asks for. */
function unreached(step: Step, flows: string[]): Set<string> {
  const keys = new Set<string>();
  const open: boolean[] = []; // per open flows block: does it include one of flows?
  for (const raw of step.markdown.split('\n')) {
    const [, , kind, rest = ''] = raw.match(DIRECTIVE) ?? [];
    if (kind === 'flows') open.push(rest.split(',').some((f) => flows.includes(f.trim())));
    else if (kind === 'end-flows') open.pop();
    else if ((kind === 'answer' || kind === 'secret') && open.includes(false)) keys.add(rest.trim());
  }
  return keys;
}

/** A step as one line of a Claude Code prompt, then one indented line per field, secret, command, check and condition that show= keeps. */
function promptStep(step: Step, format: 'claude-page' | 'claude-terminal', show = new Set(SHOW), flows?: string[]): string {
  const page = format === 'claude-page';
  const sentence = firstSentence(step);
  const out = [`- ${page ? step.id + ': ' : ''}${[step.title.replace(/\.$/, '') + '.', sentence].filter(Boolean).join(' ')}`];
  if (step.flows.length < Object.keys(FLOWS).length) out.push(`  (only for: ${step.flows.map((f) => FLOWS[f as keyof typeof FLOWS]).join('; ')})`);
  const skip = flows ? unreached(step, flows) : new Set<string>();
  if (show.has('fields')) for (const key of step.answers.filter((k) => !skip.has(k))) out.push(page ? `  they fill ${key} on the page` : `  fill ${key} in bwat.answers`);
  if (show.has('fields')) for (const key of step.secrets.filter((k) => !skip.has(k))) out.push(page ? `  they type ${key} into the page` : `  I save it with ./bwat secret ${key}`);
  if (show.has('commands')) for (const run of step.runs) out.push(page ? `  run_command ${run.id}` : `  run ${run.command.split('\n').join(' ; ')}`);
  if (show.has('checks')) for (const check of step.checks) out.push(`  (ticks itself when ${(CHECK_TEXT[check] ?? check).replace(/^This step ticks itself (when|once) /, '').replace(/\.$/, '')})`);
  if (step.when && show.has('when')) out.push(`  (only when ${CONDITIONS[step.when]?.label ?? step.when})`);
  if (step.ask) out.push(`  (optional: ask me first, "${step.ask}"; on a no, skip it)`);
  return out.join('\n');
}

const slotArgs = (text: string) => Object.fromEntries([...text.matchAll(/(\w+)=(\S+)/g)].map((m) => [m[1]!, m[2]!]));

const KEEP_START = /^<!-- bwat:keep ([\w-]+) -->$/;
const KEEP_END = '<!-- bwat:end-keep -->';
const SNIPPET_START = /^<!-- bwat:snippet ([\w-]+) -->$/;
const SNIPPET_END = '<!-- bwat:end-snippet -->';

/** The blocks between keep markers in a committed output, by name, markers included. */
function keptBlocks(committed: string): Map<string, string> {
  const blocks = new Map<string, string>();
  for (const m of committed.matchAll(/^<!-- bwat:keep ([\w-]+) -->$[\s\S]*?^<!-- bwat:end-keep -->$/gm)) blocks.set(m[1]!, m[0]);
  return blocks;
}

/** committed is the output as it stands: keep blocks are copied from it, and the template's own body is the first seed. */
export function render(template: string, master: Master, format: Format, committed = ''): string {
  const kept = keptBlocks(committed);
  const snippets = new Map<string, string>();
  const lines: string[] = [];
  let skipping = false;
  let snippet: { name: string; body: string[] } | null = null;
  let open: string | null = null;
  let seed: string[] | null = null; // the template's own lines of the open keep block
  for (const line of template.split('\n')) {
    const start = line.match(SNIPPET_START);
    if (start) { snippet = { name: start[1]!, body: [] }; continue; }
    if (snippet) {
      if (line === SNIPPET_END) { snippets.set(snippet.name, snippet.body.join('\n')); snippet = null; } else snippet.body.push(line);
      continue;
    }
    if (line === KEEP_END && open && seed && !seed.some((l) => l.trim())) throw new Error(`keep block ${open} has no committed content and the template has none to start from: restore it from git, then run ./bwat docs`);
    if (line === KEEP_END) { open = null; seed = null; }
    if (skipping) { if (line === KEEP_END) skipping = false; continue; }
    const keep = line.match(KEEP_START);
    if (keep) { open = keep[1]!; seed = []; }
    else if (open && seed) seed.push(line);
    if (keep && kept.has(keep[1]!)) {
      const block = kept.get(keep[1]!)!;
      if (!block.split('\n').slice(1, -1).some((l) => l.trim())) throw new Error(`keep block ${keep[1]} is empty in the committed file: restore it from git, then run ./bwat docs`);
      lines.push(block); skipping = true; seed = null; continue;
    }
    lines.push(line);
  }
  if (skipping || open) throw new Error(`the template's keep block ${open} has no ${KEEP_END}`);
  if (snippet) throw new Error(`the template's snippet ${snippet.name} has no ${SNIPPET_END}`);
  return lines.map((line) => {
    const slot = line.match(/^\{\{(\w+)(.*)\}\}\s*$/);
    if (!slot) return line;
    const [, kind, rest] = slot as unknown as [string, string, string];
    if (kind === 'snippet') {
      const body = snippets.get(rest.trim());
      if (body === undefined) throw new Error(`template names snippet ${rest.trim()}, which it does not define`);
      return body;
    }
    const args = slotArgs(rest);
    const allowed = kind === 'steps' ? ['ids', 'flows', 'level', 'show', 'format'] : ['level'];
    for (const key of Object.keys(args)) if (!allowed.includes(key)) throw new Error(`slot {{${kind}}} has no argument ${key}=`);
    if (!/^[0-6]$/.test(args.level ?? '3')) throw new Error(`slot {{${kind}}} has a bad level=${args.level}: use 0 to 6`);
    const level = Number(args.level ?? 3);
    if (kind === 'steps') {
      const ids = args.ids?.split(',');
      const flows = args.flows?.split(',');
      for (const flow of flows ?? []) if (!Object.hasOwn(FLOWS, flow)) throw new Error(`slot {{steps}} names unknown flow ${flow}`);
      const show = new Set(args.show ? args.show.split(',') : SHOW);
      for (const item of show) if (!SHOW.includes(item)) throw new Error(`slot {{steps}} cannot show ${item}: use ${SHOW.join(', ')}`);
      for (const id of ids ?? []) if (!master.steps.some((s) => s.id === id)) throw new Error(`template names step ${id}, which the master lacks`);
      const chosen = master.steps.filter((s) => (!ids || ids.includes(s.id)) && (!flows || s.flows.some((f) => flows.includes(f))));
      const slotFormat = args.format ?? format;
      if (!['guide', 'claude-page', 'claude-terminal'].includes(slotFormat)) throw new Error(`slot {{steps}} has a bad format=${slotFormat}: use claude-page or claude-terminal`);
      if (slotFormat !== 'guide') return chosen.map((s) => promptStep(s, slotFormat as 'claude-page' | 'claude-terminal', show, flows)).join('\n');
      return chosen.map((s) => guideStep(s, level, show)).join('\n\n');
    }
    if (kind === 'part') {
      const id = rest.trim().split(/\s/)[0]!;
      const part = master.parts.find((p) => p.id === id);
      if (!part) throw new Error(`template names part ${id}, which the master lacks`);
      const heading = level > 0 ? `${'#'.repeat(level)} ${part.title}\n\n` : '';
      return heading + guideBody(part.markdown, new Set(SHOW));
    }
    throw new Error(`unknown template slot {{${kind}}}`);
  }).join('\n').replace(/\n{3,}/g, '\n\n');
}

/** setup/paths reads this: name, path, date (YYYY-MM or empty), tab-separated, sorted by name. */
export function pathsTsv(master: Master): string {
  const lines = [...master.paths.values()].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)).map((p) => {
    if (/[\t\n]/.test(p.path)) throw new Error(`path ${p.name} holds a tab or a line break, which setup/paths cannot read`);
    return `${p.name}\t${p.path}\t${p.date ?? ''}`;
  });
  return `# Generated by ./bwat docs from docs/onboarding/master.md; edit that, then run ./bwat docs.\n${lines.join('\n')}\n`;
}

/** Every generated file with the content the master and the templates make. */
export function outputs(): { path: string; content: string }[] {
  const master = loadMaster();
  const template = (name: string) => readFileSync(join(ROOT, 'docs/onboarding/templates', name), 'utf8');
  const committed = (path: string) => (path && existsSync(join(ROOT, path)) ? readFileSync(join(ROOT, path), 'utf8') : '');
  const made = (name: string, format: Format, path = '') => `${generatedBy(name)}\n${render(template(name), master, format, committed(path)).trim()}\n`;
  return [
    { path: 'docs/setup-with-claude.md', content: made('claude.md', 'guide', 'docs/setup-with-claude.md') },
    { path: 'docs/onboarding.md', content: made('guide.md', 'guide') },
    { path: 'setup/onboard/paths.tsv', content: pathsTsv(master) },
  ];
}

/** Writes them; returns the paths whose content changed. */
export function writeOutputs(): string[] {
  const changed: string[] = [];
  for (const { path, content } of outputs()) {
    const file = join(ROOT, path);
    if (existsSync(file) && readFileSync(file, 'utf8') === content) continue;
    writeFileSync(file, content);
    changed.push(path);
  }
  return changed;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const path of writeOutputs()) console.log(`wrote ${path}`);
}
